const LARGURAS = [800, 1200, 1600, 2400];
const larguras = (k) => LARGURAS.filter((w) => w <= fotos[k].largura);

export const fotoSrc = (k, w = 1200) => {
  const ls = larguras(k);
  const melhor = ls.reduce((a, b) => (Math.abs(b - w) < Math.abs(a - w) ? b : a), ls[0]);
  return `/fotos/${fotos[k].ficheiro}-${melhor}.webp`;
};

